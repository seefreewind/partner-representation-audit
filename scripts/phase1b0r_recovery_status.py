#!/usr/bin/env python3
"""Deprecated historical Phase 1B-0R recovery script; do not use for R0R2.

This script targets the obsolete full ProtT5 identifier. The current corrected
technical-hold artifacts are generated by phase1b0r2_recovery_status.py.

This script does not infer MutPred-PPI scores or test disease-label effects. It
only verifies the frozen inputs and records every row blocked by the missing
required ProtT5 dependency.
"""
from __future__ import annotations

import hashlib
import re
from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "phase1B0R"
REPORT = ROOT / "reports" / "PHASE1B0R_DISRUPTION_SCORING_RECOVERY.md"
EXPECTED_ROWS = 11_150
MODEL_ID = "Rostlab/prot_t5_xl_uniref50"
MODEL_SHA256 = "c06141d42e93c12b5f6d95c701952156bd4079661f5f2d981d0d2036ba96dae9"
MUTPRED_VERSION = "v1.0.0"
MUTPRED_COMMIT = "a6e2f47e18a3af5dbbc4d8accce8ab177049c56c"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def write_tsv(frame: pd.DataFrame, name: str) -> None:
    frame.to_csv(OUT / name, sep="\t", index=False, na_rep="NA")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (ROOT / "reports").mkdir(parents=True, exist_ok=True)

    freeze = pd.read_csv(ROOT / "metadata/PHASE1B0_INPUT_FREEZE_MANIFEST.tsv", sep="\t")
    freeze_audit = []
    for row in freeze.itertuples(index=False):
        p = ROOT / row.path
        actual = sha256(p) if p.is_file() else "MISSING"
        freeze_audit.append({
            "path": row.path,
            "expected_sha256": row.SHA256,
            "actual_sha256": actual,
            "status": "PASS" if actual == row.SHA256 else "INPUT_FREEZE_VIOLATION",
        })
    freeze_audit = pd.DataFrame(freeze_audit)
    write_tsv(freeze_audit, "input_freeze_audit.tsv")
    if not freeze_audit.status.eq("PASS").all():
        raise SystemExit("INPUT_FREEZE_VIOLATION")

    universe_path = ROOT / "results/phase1B0/variant_partner_scoring_universe.tsv"
    universe = pd.read_csv(universe_path, sep="\t", dtype={"VariationID": str})
    if len(universe) != EXPECTED_ROWS:
        raise SystemExit(f"SCORING_UNIVERSE_MISMATCH: observed {len(universe)}")

    # Preserve the frozen training-overlap flags on every row. This merge is
    # descriptive only and has no disease-label or outcome-based filtering.
    overlap_path = ROOT / "results/phase1B0/mutpred_training_overlap.tsv"
    overlap = pd.read_csv(overlap_path, sep="\t", dtype={"VariationID": str})
    keys = ["gene", "VariationID", "partner"]
    overlap = overlap.drop_duplicates(keys)
    keep_overlap = keys + [
        "exact_variant_training_overlap",
        "exact_variant_partner_training_overlap",
        "strict_external_include",
        "protein_external_include",
    ]
    frame = universe.merge(overlap[keep_overlap], on=keys, how="left", validate="one_to_one")
    for c in keep_overlap[3:]:
        frame[c] = frame[c].fillna("UNKNOWN")

    scores = pd.DataFrame({
        "gene": frame.gene,
        "VariationID": frame.VariationID,
        "variant": frame.canonical_variant,
        "partner": frame.partner,
        "structure_id": "NA",
        "structure_candidates": frame.experimental_PDB_IDs,
        "mutated_chain": "NA",
        "partner_chain": "NA",
        "MutPred_PPI_version": MUTPRED_VERSION,
        "score": np.nan,
        "status": "NOT_SCORED_TECHNICAL_HOLD",
        "failure_reason": "PROTT5_FAILURE",
        "failure_detail": "Required ProtT5 weights were not obtained; inference was not started.",
        "disease_group": frame.disease_group,
        "exact_variant_training_overlap": frame.exact_variant_training_overlap,
        "exact_variant_partner_training_overlap": frame.exact_variant_partner_training_overlap,
        "strict_external_include": frame.strict_external_include,
        "protein_external_include": frame.protein_external_include,
    })
    write_tsv(scores, "mutpred_ppi_v1_scores.tsv")
    write_tsv(scores[[
        "gene", "VariationID", "variant", "partner", "structure_candidates",
        "MutPred_PPI_version", "status", "failure_reason", "failure_detail",
    ]], "failure_registry.tsv")

    variant_coverage = (
        scores.groupby(["gene", "VariationID", "variant"], dropna=False)
        .agg(eligible_partner_rows=("partner", "nunique"), scored_partner_rows=("score", "count"))
        .reset_index()
    )
    variant_coverage["variants_with_ge1_partner_score"] = variant_coverage.scored_partner_rows.ge(1)
    variant_coverage["variants_with_ge3_partner_scores"] = variant_coverage.scored_partner_rows.ge(3)
    variant_coverage["status"] = "NOT_EVALUABLE_TECHNICAL_HOLD"
    write_tsv(variant_coverage, "coverage_by_variant.tsv")

    structural = pd.read_csv(ROOT / "results/phase1B0/structural_42_genes.tsv", sep="\t")
    protein_map = pd.read_csv(
        ROOT / "results/phase1A/protein_mapping.tsv", sep="\t", dtype={"VariationID": str}
    )
    mondo_count = protein_map["MONDOs"].fillna("").astype(str).str.count(r"MONDO:")
    single_label = protein_map[
        protein_map.primary_cohort_eligible.astype(str).str.upper().eq("YES") & mondo_count.eq(1)
    ]
    primary_variant_n = single_label.groupby("gene").VariationID.nunique().to_dict()
    rows_by_gene = scores.groupby("gene").size().to_dict()
    vars_by_gene = scores.groupby("gene").VariationID.nunique().to_dict()
    gene_rows = []
    for gene in structural.gene.astype(str):
        den = int(primary_variant_n.get(gene, 0))
        pct = 0.0 if den else np.nan
        gene_rows.append({
            "gene": gene,
            "eligible_single_label_primary_variants": den,
            "input_variant_partner_rows": int(rows_by_gene.get(gene, 0)),
            "input_variants": int(vars_by_gene.get(gene, 0)),
            "scored_rows": 0,
            "variants_ge1_partner_score": 0,
            "variants_ge3_partner_scores": 0,
            "primary_variant_ge3_coverage_pct": pct,
            "passes_70pct_disruption_representation": "NO" if den else "NOT_ASSESSABLE_NO_DENOMINATOR",
            "status": "TECHNICAL_HOLD_NO_MODEL_SCORES",
        })
    gene_coverage = pd.DataFrame(gene_rows)
    write_tsv(gene_coverage, "coverage_by_gene.tsv")

    prior_diff = pd.read_csv(
        ROOT / "results/phase1B0/differential_coverage_adjudication.tsv", sep="\t"
    )
    prior_flags = set(prior_diff.loc[
        prior_diff.gene_coverage_adjudication.astype(str).str.upper().isin(
            ["SEVERE_IMBALANCE", "MATERIAL_IMBALANCE"]
        ), "gene"
    ].astype(str))
    diff = pd.DataFrame({"gene": structural.gene.astype(str)})
    diff["pre_scoring_representation_imbalance_flag"] = diff.gene.map(
        lambda g: "YES" if g in prior_flags else "NO"
    )
    diff["differential_score_coverage_status"] = "PENDING_NO_VALID_MUTPRED_SCORES"
    diff["score_coverage_recomputed"] = "NO"
    diff["note"] = "Global ProtT5 dependency hold; disease-specific score completeness was not adjudicated."
    write_tsv(diff, "differential_score_coverage.tsv")

    write_tsv(pd.DataFrame([{
        "rebuild_status": "NOT_REBUILT_PREREQUISITE_NOT_MET",
        "reason": "Primary cohort rebuild requires validated MutPred-PPI scores.",
        "rebuilt_primary_gene_count": "NA",
        "strict_external_gene_count": "NA",
        "disease_label_association_testing": "NOT_STARTED",
    }]), "rebuilt_primary_cohort.tsv")

    write_tsv(pd.DataFrame([{
        "example": "official v1.0.0 release example",
        "reference_rows": 10,
        "rows_scored": 0,
        "max_abs_difference": "NA",
        "status": "NOT_RUN_PROTT5_WEIGHTS_UNAVAILABLE",
    }]), "official_example_validation.tsv")
    for n in (20, 100):
        write_tsv(pd.DataFrame([{
            "pilot_size": n,
            "rows_scored": 0,
            "status": "NOT_RUN_PROTT5_WEIGHTS_UNAVAILABLE",
            "failure_reason": "PROTT5_FAILURE",
            "selection": "No pilot selected or executed before prerequisite validation.",
        }]), f"pilot{n}.tsv")
    write_tsv(pd.DataFrame([{
        "batch_id": "NONE",
        "rows_attempted_in_model": 0,
        "rows_scored": 0,
        "rows_blocked": EXPECTED_ROWS,
        "primary_failure_reason": "PROTT5_FAILURE",
        "status": "BLOCKED_BEFORE_BATCHING",
    }]), "batch_manifest.tsv")

    write_tsv(pd.DataFrame(columns=[
        "sequence_id", "sequence_sha256", "model", "embedding_path_or_cache_key",
        "success", "length", "timestamp",
    ]), "prott5_embedding_manifest.tsv")
    download_rows = []
    expected_files = [
        "config.json", "spiece.model", "tokenizer_config.json",
        "special_tokens_map.json", "pytorch_model.bin",
    ]
    for filename in expected_files:
        download_rows.append({
            "model_id": MODEL_ID,
            "filename": filename,
            "expected_sha256": MODEL_SHA256 if filename == "pytorch_model.bin" else "NOT_PUBLISHED_HERE",
            "local_path": str(ROOT / "data/software/models/prot_t5_xl_uniref50" / filename),
            "bytes_obtained": 0,
            "actual_sha256": "NOT_OBTAINED",
            "status": "NOT_DOWNLOADED",
            "method": "official hf CLI standard path attempted",
            "failure": "huggingface.co metadata request failed with SSLEOFError before file transfer",
        })
    write_tsv(pd.DataFrame(download_rows), "prott5_download_manifest.tsv")

    dependencies = [
        ("MutPred-PPI", MUTPRED_VERSION, MUTPRED_VERSION, "SOURCE_AND_TEN_CHECKPOINTS_PRESENT"),
        ("MutPred-PPI_source_commit", "v1.0.0", MUTPRED_COMMIT, "VERIFIED"),
        ("ProtT5_model_id", MODEL_ID, MODEL_ID, "WEIGHTS_UNAVAILABLE"),
        ("ProtT5_pytorch_model.bin", MODEL_SHA256, "NOT_OBTAINED", "HF_TLS_FAILURE"),
        ("Python_inference_environment", "Python 3.10+ dedicated", "venv creation started; install interrupted", "INCOMPLETE"),
        ("Existing_HF_CLI", "hf CLI available", "huggingface_hub 0.36.2; hf --help succeeds", "AVAILABLE_BUT_NETWORK_BLOCKED"),
        ("Global_torch", "not used for production", "2.8.0 (Python 3.9.6)", "INSPECTED_ONLY"),
        ("Global_transformers", "not used for production", "4.48.1 (Python 3.9.6)", "INSPECTED_ONLY"),
        ("Global_sentencepiece", "not used for production", "0.2.0 (Python 3.9.6)", "INSPECTED_ONLY"),
        ("CUDA", "optional", "unavailable", "CPU_ONLY_IF_RETRIED"),
    ]
    write_tsv(pd.DataFrame(dependencies, columns=["component", "expected", "observed", "status"]), "dependency_manifest.tsv")

    primary_flags = len(prior_flags)
    report = f"""# PHASE 1B-0R — MutPred-PPI / ProtT5 Scoring Recovery

## Verdict

**TECHNICAL_HOLD_DISRUPTION_SCORING**

The required ProtT5 full PyTorch checkpoint was not obtained. No MutPred-PPI inference call, official example scoring, pilot, or production batch was started. The failure is technical and does not support a biological or structural NO-GO.

## Frozen-input audit

- Phase 1A freeze manifest: {len(freeze_audit)} files checked; {int(freeze_audit.status.eq('PASS').sum())} matched; no `INPUT_FREEZE_VIOLATION`.
- Frozen variant–partner scoring universe: {len(universe):,} rows (required 11,150); unchanged.
- The frozen training-overlap flags were carried into the row-level recovery status file. No rows were removed.

## Version and model artifacts

- Primary MutPred-PPI version: **v1.0.0**.
- Exact source commit: `{MUTPRED_COMMIT}` (official `v1.0.0` tag).
- Ten tagged v1.0 ensemble checkpoints and their scaler are present under `data/software/mutpred-ppi-v1.0.0/models/`; SHA256 records are in `results/phase1B0R/mutpred_v1_model_checksums.tsv`.
- Requested ProtT5 model: `{MODEL_ID}`. The official model page reports `pytorch_model.bin` SHA256 `{MODEL_SHA256}` and size about 11.3 GB ([Hugging Face model file](https://huggingface.co/Rostlab/prot_t5_xl_uniref50/blob/main/pytorch_model.bin)). No local weight file was obtained.
- Source expectation conflict recorded: the tagged v1.0 loader defaults to `Rostlab/prot_t5_xl_half_uniref50-enc`; this recovery followed the explicit full-model target and did not substitute the half encoder. The full model therefore requires end-to-end validation against the tagged example before scoring.

## Download and environment recovery

- Official `hf download` standard path was attempted for `config.json`, `spiece.model`, tokenizer files, and `pytorch_model.bin`.
- Failure occurred before metadata resolution: `huggingface.co` returned `SSLEOFError` / `SSL_ERROR_SYSCALL`; no Xet file transfer began. The external-DNS HTTPS diagnostic also failed before returning a usable official address. Xet fallback was not appropriate because the failure preceded Xet handoff.
- Download log: `logs/phase1B0R_prott5_download.log`.
- `hf --help` succeeds; the available CLI uses `huggingface_hub 0.36.2`. A dedicated Python 3.10.20 environment installation was started and interrupted during external-volume I/O before a verified environment was available. Exact state is in `dependency_manifest.tsv` and `logs/phase1B0R_environment_install.log`.
- Storage was sufficient for the requested download; the failure was endpoint connectivity, not disk capacity.

## Scoring and coverage status

- Successfully scored: **0 / 11,150**; row coverage **0.00%**.
- Variants with at least one partner score: **0**; with at least three: **0**.
- Structural genes with observed ≥70% disruption representation: **0** because no score was produced; this is a technical missingness result, not an intrinsic representation finding.
- Most common row status reason: `PROTT5_FAILURE` (11,150 rows). Each input row remains present in `mutpred_ppi_v1_scores.tsv` and `failure_registry.tsv` with an explicit status.
- Official example, pilot-20, pilot-100, and production batching were **not run** because the required model was unavailable.
- The {primary_flags} pre-scoring representation-imbalance genes remain unresolved. Differential score coverage was not reassessed without valid scores.
- Primary and strict-external cohorts were **not rebuilt**. The old Phase 1B-0 zero-gene cohort result was not carried forward as a new result.
- Coverage summaries are technical completeness outputs only; no disease-specific score comparison or disease-label association test was run.

## Required output inventory

`results/phase1B0R/` contains the requested manifests, row-level status table, failure registry, coverage tables, blocked validation/pilot records, and a non-rebuilt cohort status record. The ProtT5 embedding manifest is empty because no sequence was embedded.

## Stop point

Do not start Phase 1B-1. Resume Phase 1B-0R only after the exact full ProtT5 model can be retrieved from the official host, loaded locally, and the official v1.0 example passes the frozen numerical tolerance. Disease-label association testing was NOT started.
"""
    REPORT.write_text(report, encoding="utf-8")

    print(f"input_rows={len(universe)}")
    print(f"input_freeze_files={len(freeze_audit)} input_freeze_issues=0")
    print(f"scores=0 row_coverage=0.00% variants={len(variant_coverage)}")
    print(f"structural_genes={len(structural)} prior_differential_flags={primary_flags}")
    print(f"report={REPORT}")


if __name__ == "__main__":
    main()
